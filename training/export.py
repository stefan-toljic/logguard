"""INT8-quantize a trained model and generate the firmware headers.

    python export.py --run runs/ds_cnn

Checks (fails loudly):
  * INT8 window F1 within --max-drop (default 3 points) of float
  * model file under --max-kb (default 40 KB)
  * every op in the model is registered in the firmware op resolver

Writes into firmware/main/generated/:
  model_data.cc / model_data.h  the .tflite as a C array
  model_meta.h                  CHAINSAW_IDX, feature mean/std, threshold
  selftest_vectors.h            PCM + expected MFCC + expected INT8 output (test T1)
  mfcc_tables.h                 window, mel filterbank, DCT (from features.py)
"""
import argparse
import json
import os
import sys

import numpy as np

from logguard import dataset as D
from logguard import features as F
from logguard import metrics, synthetic

HERE = os.path.dirname(os.path.abspath(__file__))
GEN_DIR = os.path.join(HERE, "..", "firmware", "main", "generated")

# Must match the resolver in firmware/main/detector.cc
FIRMWARE_OPS = {"CONV_2D", "DEPTHWISE_CONV_2D", "FULLY_CONNECTED", "SOFTMAX",
                "MEAN", "RESHAPE", "AVERAGE_POOL_2D", "QUANTIZE", "DEQUANTIZE"}


def quantize(model, rep):
    import tensorflow as tf

    def rep_gen():
        for i in range(len(rep)):
            yield [rep[i:i + 1].astype(np.float32)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep_gen
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    return conv.convert()


class Int8Model:
    def __init__(self, tflite_bytes):
        import tensorflow as tf
        self.it = tf.lite.Interpreter(
            model_content=tflite_bytes,
            experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
        self.it.allocate_tensors()
        self.inp = self.it.get_input_details()[0]
        self.out = self.it.get_output_details()[0]
        self.in_scale, self.in_zp = self.inp["quantization"]
        self.out_scale, self.out_zp = self.out["quantization"]

    def ops(self):
        return {op["op_name"] for op in self.it._get_ops_details()}

    def quantize_input(self, x):
        q = np.round(x / self.in_scale + self.in_zp)
        return np.clip(q, -128, 127).astype(np.int8)

    def raw(self, xq):
        self.it.set_tensor(self.inp["index"], xq[np.newaxis])
        self.it.invoke()
        return self.it.get_tensor(self.out["index"])[0]

    def probs(self, x):
        return np.stack([(self.raw(self.quantize_input(w)).astype(np.float32)
                          - self.out_zp) * self.out_scale for w in x])


def c_bytes(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return (f"alignas(16) const unsigned char {name}[] = {{\n  " + ",\n  ".join(rows)
            + f"\n}};\nconst unsigned int {name}_len = {len(data)};\n")


def c_floats(name, arr):
    return f"static const float {name}[{len(arr)}] = {{{', '.join(f'{v:.9e}f' for v in arr)}}};\n"


def c_ints(ctype, name, arr, per_line=16):
    arr = np.asarray(arr).ravel()
    rows = [", ".join(str(int(v)) for v in arr[i:i + per_line]) for i in range(0, len(arr), per_line)]
    return f"static const {ctype} {name}[{len(arr)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def selftest_pcm():
    """Two deterministic 1 s int16 windows for the T1 parity test."""
    rng = np.random.default_rng(1234)
    out = []
    for gen in (synthetic.chainsaw_like, synthetic.environment_like):
        w = F.windows(D.resample(gen(rng, sr=16000, seconds=1.0), 16000))[0]
        out.append(np.clip(np.round(w * 32767), -32768, 32767).astype(np.int16))
    return out


def write_headers(tflite_bytes, m, mean, std, threshold, gen_dir, report):
    os.makedirs(gen_dir, exist_ok=True)
    F.export_tables(os.path.join(gen_dir, "mfcc_tables.h"))
    with open(os.path.join(gen_dir, "model_data.cc"), "w") as f:
        f.write('// Generated by training/export.py. Do not edit by hand.\n'
                '#include "model_data.h"\n' + c_bytes("g_model_data", tflite_bytes))
    with open(os.path.join(gen_dir, "model_data.h"), "w") as f:
        f.write("#pragma once\nextern const unsigned char g_model_data[];\n"
                "extern const unsigned int g_model_data_len;\n")
    with open(os.path.join(gen_dir, "model_meta.h"), "w") as f:
        f.write("// Generated by training/export.py. Do not edit by hand.\n#pragma once\n\n"
                f"// Model output index of the chainsaw class. Dataset rfcx/frugalai uses\n"
                f"// label {D.DATASET_CHAINSAW_LABEL} = chainsaw; training remaps it to index {D.CHAINSAW_IDX}.\n"
                f"#define MODEL_CHAINSAW_IDX {D.CHAINSAW_IDX}\n"
                f"#define MODEL_N_CLASSES 2\n"
                f"// Default probability threshold (Kconfig can override).\n"
                f"#define MODEL_DEFAULT_THRESHOLD {threshold:.3f}f\n"
                f"// Ops in this model: {', '.join(sorted(m.ops()))}\n"
                f"// Export report: {json.dumps(report)}\n\n"
                + c_floats("model_feat_mean", mean) + c_floats("model_feat_std", std))
    pcm = selftest_pcm()
    parts = ["// Generated by training/export.py. Do not edit by hand.\n#pragma once\n#include <stdint.h>\n\n",
             f"#define SELFTEST_N {len(pcm)}\n"]
    for i, w in enumerate(pcm):
        feats = F.mfcc(w.astype(np.float32) / 32768.0)
        xq = m.quantize_input(((feats - mean) / std)[..., np.newaxis])
        raw = m.raw(xq)
        parts += [c_ints("int16_t", f"selftest_pcm_{i}", w),
                  c_floats(f"selftest_mfcc_{i}", feats.ravel()),
                  c_ints("int8_t", f"selftest_out_{i}", raw)]
    parts.append("static const int16_t *const selftest_pcm[SELFTEST_N] = {%s};\n"
                 % ", ".join(f"selftest_pcm_{i}" for i in range(len(pcm))))
    parts.append("static const float *const selftest_mfcc[SELFTEST_N] = {%s};\n"
                 % ", ".join(f"selftest_mfcc_{i}" for i in range(len(pcm))))
    parts.append("static const int8_t *const selftest_out[SELFTEST_N] = {%s};\n"
                 % ", ".join(f"selftest_out_{i}" for i in range(len(pcm))))
    with open(os.path.join(gen_dir, "selftest_vectors.h"), "w") as f:
        f.write("".join(parts))


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--run", required=True, help="directory written by train.py")
    p.add_argument("--gen-dir", default=GEN_DIR)
    p.add_argument("--max-drop", type=float, default=0.03)
    p.add_argument("--max-kb", type=float, default=40)
    p.add_argument("--threshold", type=float, default=0.8)
    a = p.parse_args(argv)

    import tensorflow as tf
    model = tf.keras.models.load_model(os.path.join(a.run, "model.keras"))
    norm = np.load(os.path.join(a.run, "norm.npz"))
    mean, std = norm["mean"], norm["std"]
    data = np.load(os.path.join(a.run, "data.npz"))
    n = lambda z: ((z - mean) / std)[..., np.newaxis].astype(np.float32)

    tflite_bytes = quantize(model, n(data["rep"]))
    with open(os.path.join(a.run, "chainsaw.tflite"), "wb") as f:
        f.write(tflite_bytes)
    m = Int8Model(tflite_bytes)

    Xt, yt, cidt = n(data["Xt"]), data["yt"], data["cidt"]
    pf = model.predict(Xt, verbose=0)[:, D.CHAINSAW_IDX]
    pq = m.probs(Xt)[:, D.CHAINSAW_IDX]
    rf, rq = metrics.report(yt, pf, cidt), metrics.report(yt, pq, cidt)
    size_kb = len(tflite_bytes) / 1024
    report = {"float": rf, "int8": rq, "size_kb": round(size_kb, 1),
              "in_scale": float(m.in_scale), "in_zp": int(m.in_zp)}
    print(json.dumps(report, indent=2))

    errors = []
    if rf["window_f1"] - rq["window_f1"] > a.max_drop:
        errors.append(f"INT8 F1 drop {rf['window_f1'] - rq['window_f1']:.3f} > {a.max_drop}: "
                      "widen the representative set (rep_gen) before blaming hardware")
    if size_kb > a.max_kb:
        errors.append(f"model is {size_kb:.1f} KB > {a.max_kb} KB")
    missing = m.ops() - FIRMWARE_OPS
    if missing:
        errors.append(f"ops not registered in firmware: {sorted(missing)}")
    if errors:
        sys.exit("export failed:\n  " + "\n  ".join(errors))

    write_headers(tflite_bytes, m, mean, std, a.threshold, a.gen_dir, report)
    print(f"wrote headers to {os.path.abspath(a.gen_dir)}")


if __name__ == "__main__":
    main()
