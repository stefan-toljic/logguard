"""MFCC front end shared by training and firmware.

This module is the single source of truth for the features. The firmware
(firmware/main/mfcc.c) uses the exact same window, mel filterbank and DCT
matrices, exported by `export_tables()` into firmware/main/mfcc_tables.h,
so the device computes the same numbers the model was trained on.

No librosa: every step is written out so it can be mirrored line by line in C.
"""
import numpy as np

SAMPLE_RATE = 16000
WIN_SAMPLES = SAMPLE_RATE          # 1 s analysis window
HOP_WINDOW = SAMPLE_RATE // 2      # 0.5 s between windows (training and firmware)
N_FFT = 512
HOP = 320                          # 20 ms
N_MELS = 40
N_MFCC = 40
N_FRAMES = 1 + (WIN_SAMPLES - N_FFT) // HOP   # 49, no centre padding
N_BINS = N_FFT // 2 + 1                        # 257
FMIN, FMAX = 20.0, 8000.0
LOG_EPS = 1e-6


def hann_window():
    # Periodic Hann, same as scipy.signal.get_window("hann", N_FFT)
    n = np.arange(N_FFT)
    return (0.5 - 0.5 * np.cos(2 * np.pi * n / N_FFT)).astype(np.float32)


def _hz_to_mel(f):
    return 2595.0 * np.log10(1.0 + f / 700.0)


def _mel_to_hz(m):
    return 700.0 * (10.0 ** (m / 2595.0) - 1.0)


def mel_filterbank():
    """Triangular HTK mel filters, shape (N_MELS, N_BINS)."""
    mels = np.linspace(_hz_to_mel(FMIN), _hz_to_mel(FMAX), N_MELS + 2)
    hz = _mel_to_hz(mels)
    bins = np.linspace(0, SAMPLE_RATE / 2, N_BINS)
    fb = np.zeros((N_MELS, N_BINS), dtype=np.float64)
    for m in range(N_MELS):
        lo, centre, hi = hz[m], hz[m + 1], hz[m + 2]
        up = (bins - lo) / (centre - lo)
        down = (hi - bins) / (hi - centre)
        fb[m] = np.maximum(0.0, np.minimum(up, down))
    return fb.astype(np.float32)


def dct_matrix():
    """Orthonormal DCT-II, shape (N_MFCC, N_MELS)."""
    k = np.arange(N_MFCC)[:, None]
    n = np.arange(N_MELS)[None, :]
    d = np.cos(np.pi / N_MELS * (n + 0.5) * k) * np.sqrt(2.0 / N_MELS)
    d[0] *= 1.0 / np.sqrt(2.0)
    return d.astype(np.float32)


_WINDOW = hann_window()
_MEL = mel_filterbank()
_DCT = dct_matrix()


def mfcc(window):
    """1 s float32 PCM in [-1, 1] -> (N_FRAMES, N_MFCC) float32."""
    x = np.asarray(window, dtype=np.float32)
    if x.shape != (WIN_SAMPLES,):
        raise ValueError(f"expected {WIN_SAMPLES} samples, got {x.shape}")
    idx = np.arange(N_FFT)[None, :] + HOP * np.arange(N_FRAMES)[:, None]
    frames = x[idx] * _WINDOW
    spec = np.fft.rfft(frames, n=N_FFT, axis=1)
    power = (spec.real ** 2 + spec.imag ** 2).astype(np.float32)
    mel = power @ _MEL.T
    logmel = np.log(mel + LOG_EPS)
    return (logmel @ _DCT.T).astype(np.float32)


def windows(clip):
    """Split a clip (16 kHz) into 1 s windows every 0.5 s.

    Uses the whole clip, not just the first second. A clip shorter than
    1 s is zero-padded to one window.
    """
    clip = np.asarray(clip, dtype=np.float32)
    if len(clip) < WIN_SAMPLES:
        clip = np.pad(clip, (0, WIN_SAMPLES - len(clip)))
    starts = range(0, len(clip) - WIN_SAMPLES + 1, HOP_WINDOW)
    return [clip[s:s + WIN_SAMPLES] for s in starts]


def _c_array(name, arr, per_line=8):
    flat = np.asarray(arr, dtype=np.float32).ravel()
    body = ",\n".join(
        "    " + ", ".join(f"{v:.9e}f" for v in flat[i:i + per_line])
        for i in range(0, len(flat), per_line))
    return f"static const float {name}[{len(flat)}] = {{\n{body}\n}};\n"


def export_tables(path):
    """Write the C header with the window, mel filterbank and DCT."""
    # Store the filterbank sparsely: each triangle covers a few bins only.
    starts, lengths, weights = [], [], []
    for row in _MEL:
        nz = np.nonzero(row)[0]
        starts.append(int(nz[0]))
        lengths.append(int(nz[-1] - nz[0] + 1))
        weights.extend(row[nz[0]:nz[-1] + 1])
    out = [
        "// Generated by training/logguard/features.py. Do not edit by hand.\n",
        "#pragma once\n#include <stdint.h>\n\n",
        f"#define MFCC_SAMPLE_RATE {SAMPLE_RATE}\n",
        f"#define MFCC_WIN_SAMPLES {WIN_SAMPLES}\n",
        f"#define MFCC_HOP_WINDOW {HOP_WINDOW}\n",
        f"#define MFCC_N_FFT {N_FFT}\n#define MFCC_HOP {HOP}\n",
        f"#define MFCC_N_MELS {N_MELS}\n#define MFCC_N_MFCC {N_MFCC}\n",
        f"#define MFCC_N_FRAMES {N_FRAMES}\n#define MFCC_N_BINS {N_BINS}\n",
        f"#define MFCC_LOG_EPS {LOG_EPS:.9e}f\n\n",
        _c_array("mfcc_window", _WINDOW),
        "static const uint16_t mfcc_mel_start[%d] = {%s};\n"
        % (N_MELS, ", ".join(map(str, starts))),
        "static const uint16_t mfcc_mel_len[%d] = {%s};\n"
        % (N_MELS, ", ".join(map(str, lengths))),
        _c_array("mfcc_mel_weights", weights),
        _c_array("mfcc_dct", _DCT),
    ]
    with open(path, "w") as f:
        f.write("".join(out))
